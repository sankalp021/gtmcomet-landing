// Generates src/data/land.ts: a dot lattice of the land between East Africa and
// the Bay of Bengal, used by the hero canvas.
//
// The source is Natural Earth's physical "land" layer (via world-atlas), which
// has coastlines only. No country borders are read or drawn, on purpose.
//
// Run: npm run build:map
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = JSON.parse(
  readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"),
);
const land = feature(topo, topo.objects.land);

// Lattice definition. Shared with the client through the generated file.
const LAT0 = 22; // reference latitude for the equirectangular projection
const K = Math.cos((LAT0 * Math.PI) / 180);
const STEP_LAT = 0.8;
const STEP_LON = STEP_LAT / K; // equal spacing once projected
const LON_MIN = 20;
const LON_MAX = 110;
const LAT_MIN = -8;
const LAT_MAX = 48;

const cols = Math.floor((LON_MAX - LON_MIN) / STEP_LON);
const rows = Math.floor((LAT_MAX - LAT_MIN) / STEP_LAT);

// Each row is stored as [start, length, start, length, ...] runs of land dots.
const runs = [];
let count = 0;
for (let r = 0; r < rows; r++) {
  const lat = LAT_MAX - r * STEP_LAT;
  const offset = r % 2 ? STEP_LON / 2 : 0; // triangular lattice
  const row = [];
  let start = -1;
  for (let c = 0; c <= cols; c++) {
    const lon = LON_MIN + c * STEP_LON + offset;
    const inside = c < cols && geoContains(land, [lon, lat]);
    if (inside && start < 0) start = c;
    if (!inside && start >= 0) {
      row.push(start, c - start);
      count += c - start;
      start = -1;
    }
  }
  runs.push(row);
}

const out = `// Generated by scripts/build-map.mjs. Do not edit by hand.
// Physical land only (coastlines); no political boundaries are encoded.
export const LAND = {
  lat0: ${LAT0},
  stepLat: ${STEP_LAT},
  stepLon: ${STEP_LON.toFixed(6)},
  lonMin: ${LON_MIN},
  latMax: ${LAT_MAX},
  count: ${count},
  // rows[r] = [startCol, length, startCol, length, ...]
  rows: ${JSON.stringify(runs)} as number[][],
} as const;
`;
writeFileSync(new URL("../src/data/land.ts", import.meta.url), out);
console.log(`land dots: ${count}, rows: ${rows}, cols: ${cols}`);
